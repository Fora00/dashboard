// One-off extraction of the Backend Interview Lab prototype's content array `M`
// into src/projects/learning/courses/backend-interview-lab.modules.ts.
// The prototype HTML is read-only source; re-run only if it changes:
//   node scripts/learning/extract-bil.mjs <path-to-backend-interview-lab.html>
import fs from 'node:fs'
import vm from 'node:vm'

const [src] = process.argv.slice(2)
if (!src) {
  console.error('usage: node scripts/learning/extract-bil.mjs <backend-interview-lab.html>')
  process.exit(1)
}
const html = fs.readFileSync(src, 'utf8')
const script = html.match(/<script>([\s\S]*?)<\/script>/)[1]
const start = script.indexOf('var M = [')
const end = script.indexOf('/* ---------- STATE ---------- */')
const ctx = {}
vm.createContext(ctx)
vm.runInContext(script.slice(start, end), ctx)
const M = vm.runInContext('M', ctx)

const modules = M.map((m) => ({
  id: m.id,
  title: m.t,
  subtitle: m.s,
  ...(m.grp ? { group: m.grp } : {}),
  vault: m.vault,
  lesson: m.lesson,
  quiz: m.quiz.map((q, i) => ({ id: `q${i + 1}`, q: q.q, options: q.o, answer: q.a, explanation: q.e })),
  cards: m.cards.map((c, i) => ({ id: `c${i + 1}`, front: c.f, back: c.b })),
  practice: m.mock.map((p, i) => ({ id: `p${i + 1}`, question: p.q, answer: p.a })),
}))

const out = `// GENERATED by scripts/learning/extract-bil.mjs from the Backend Interview Lab
// prototype. Italian study material; lesson/quiz/card text carries light HTML
// that is sanitised at render time (sanitizeHtml.ts). Do not edit by hand.
import type { CourseModule } from '../types'

export const modules: CourseModule[] = ${JSON.stringify(modules, null, 2)}
`
fs.mkdirSync('src/projects/learning/courses', { recursive: true })
fs.writeFileSync('src/projects/learning/courses/backend-interview-lab.modules.ts', out)
console.log(
  modules.map((m) => `${m.id}:${m.group ?? '-'} q${m.quiz.length} c${m.cards.length} p${m.practice.length}`).join('\n'),
)
