// Subcategories: a finer split of the four big categories (theatre, concerts,
// exhibitions, talks). Optional on an event and conservative on purpose: an
// event that no rule recognises has NO subcategory (never a guess, no "altro"
// bucket). Other categories never get one. The ids are published in
// events.json (`subcategory`), the app mirrors the SUBCATEGORIES map for its
// chips — keep the two in sync and add ids only (docs/EVENTS.md).
//
// Rules are tried in tiers, the title alone first, then title + summary, then
// the source's own character (Mart is an art museum…); inside a tier the
// order of the list is the priority. Keyword syntax is the one of tags.ts
// ('word', 'prefix*', multi-word phrases; accents and punctuation ignored).
// The long description is never read: it name-drops every genre.
