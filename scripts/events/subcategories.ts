/** Season / festival programmes ('Stagione 2026/2027', 'Prestagione', 'Rassegna'). */
const SEASON = /(?:^| )(?:pre)?stagion[ei]|(?:^| )rassegna(?= |$)/

const compileAll = (words: string[] | undefined) => (words ?? []).map(compile)
const COMPILED = new Map(
  Object.entries(RULES).map(([category, rules]) => [
    category,
    (rules ?? []).map((r) => ({
      id: r.id,
      kids: r.kids ?? false,
      head: compileAll(r.head),
      short: compileAll(r.short),
      unless: compileAll(r.unless),
      sources: r.sources ?? [],
    })),
  ]),
)

/**
 * The subcategory of an event, or undefined: only for the categories of
 * SUBCATEGORIES, and only when a rule recognises it. Pure, so it can be
 * re-run on records carried over from an older events.json.
 */
export function subcategoryOf(
  e: Pick<Event, 'category' | 'title' | 'summary' | 'tags' | 'source'> & { sources?: string[] },
): string | undefined {
  const rules = COMPILED.get(e.category)
  if (!rules) return undefined
  const head = hayOf([e.title])
  const short = hayOf([e.title, e.summary])
  const ok = (r: (typeof rules)[number]) => !r.unless.some((p) => p.test(short))
  const hit = (words: RegExp[], hay: string) => words.some((p) => p.test(hay))
  const tagged = (r: (typeof rules)[number]) => r.kids && e.tags.includes('kids')
  const byTitle = rules.find((r) => ok(r) && hit(r.head, head))?.id
  // "Teatro di Rovereto | Stagione 2026/2027": a season lists every genre in
  // its blurb, so only its own title can classify it.
  if (!byTitle && SEASON.test(head)) return undefined
  return (
    rules.find((r) => ok(r) && tagged(r))?.id ??
    byTitle ??
    rules.find((r) => ok(r) && hit(r.short, short))?.id ??
    rules.find((r) => r.sources.includes(e.source) || r.sources.some((s) => e.sources?.includes(s)))?.id
  )
}

/** The event with `subcategory` set (or removed when no rule recognises it). */
export function withSubcategory(e: Event): Event {
  const { subcategory: _old, ...rest } = e
  const sub = subcategoryOf(e)
  return sub ? { ...rest, subcategory: sub } : rest
}
